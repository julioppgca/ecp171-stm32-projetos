#include <stdint.h>

uint8_t  soma8 (uint8_t  a, uint8_t  b) { return a + b; }
uint16_t soma16(uint16_t a, uint16_t b) { return a + b; }
uint32_t soma32(uint32_t a, uint32_t b) { return a + b; }
uint32_t mult32(uint32_t a, uint32_t b) { return a * b; }
float    multf (float    a, float    b) { return a * b; }
